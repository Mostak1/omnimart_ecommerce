                @unlink($f);
                $deleted[] = basename($f);
            }
        }
        echo "<div style='background:#d4edda;color:#155724;padding:15px;margin-bottom:20px;border-radius:5px;'>";
        echo "<b>Cache files deleted:</b> " . (count($deleted) ? implode(', ', $deleted) : 'None found') . "<br>";
        echo "</div>";
    } elseif ($_GET['action'] === 'force_repair') {
        $repairs = repairComposerAutoloader(true);
        echo "<div style='background:#d4edda;color:#155724;padding:15px;margin-bottom:20px;border-radius:5px;'>";
        echo "<b>Autoloader Force-Repaired:</b> " . implode('<br>', $repairs) . "<br>";
        echo "</div>";
    }
}

if (!empty($autoRepairs)) {
    echo "<div style='background:#d4edda;color:#155724;padding:15px;margin-bottom:20px;border-radius:5px;'>";
    echo "<b>&#10004; Autoloader Auto-Repaired:</b> " . implode('<br>', $autoRepairs) . "<br>";
    echo "</div>";
}

