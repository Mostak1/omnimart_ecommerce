<?php
ini_set('display_errors', '1');
ini_set('display_startup_errors', '1');
error_reporting(E_ALL);

$composerDir = __DIR__ . '/../vendor/composer';
$realFile = $composerDir . '/autoload_real.php';
$staticFile = $composerDir . '/autoload_static.php';
$mainAutoloadFile = __DIR__ . '/../vendor/autoload.php';

function repairComposerAutoloader($forceDynamic = false) {
    global $composerDir, $realFile, $staticFile, $mainAutoloadFile;
    $msg = [];

    if (!is_dir($composerDir)) {
        return ["Error: vendor/composer directory not found!"];
    }

    if ($forceDynamic || !file_exists($staticFile)) {
        // Write universal dynamic autoloader that requires NO hash and never fails
        $cleanReal = '<?php
// Universal Hash-Independent Autoloader @generated by OmniMart Repair
class ComposerAutoloaderUniversal
{
    private static $loader;

    public static function getLoader()
    {
        if (null !== self::$loader) {
            return self::$loader;
        }

        if (file_exists(__DIR__ . "/ClassLoader.php")) {
            require_once __DIR__ . "/ClassLoader.php";
        }
        if (file_exists(__DIR__ . "/platform_check.php")) {
            @require_once __DIR__ . "/platform_check.php";
        }

        self::$loader = $loader = new \Composer\Autoload\ClassLoader(dirname(__DIR__));

        if (file_exists(__DIR__ . "/autoload_namespaces.php")) {
            $map = require __DIR__ . "/autoload_namespaces.php";
            foreach ($map as $namespace => $path) {
                $loader->set($namespace, $path);
            }
        }

        if (file_exists(__DIR__ . "/autoload_psr4.php")) {
            $map = require __DIR__ . "/autoload_psr4.php";
            foreach ($map as $namespace => $path) {
                $loader->setPsr4($namespace, $path);
            }
        }

        if (file_exists(__DIR__ . "/autoload_classmap.php")) {
            $classMap = require __DIR__ . "/autoload_classmap.php";
            if ($classMap) {
                $loader->addClassMap($classMap);
            }
        }

        $loader->register(true);

        if (file_exists(__DIR__ . "/autoload_files.php")) {
            $filesToLoad = require __DIR__ . "/autoload_files.php";
            foreach ($filesToLoad as $fileIdentifier => $file) {
                if (empty($GLOBALS["__composer_autoload_files"][$fileIdentifier])) {
                    $GLOBALS["__composer_autoload_files"][$fileIdentifier] = true;
                    if (file_exists($file)) {
                        require $file;
                    }
                }
            }
        }

        return $loader;
    }
}
';
        file_put_contents($realFile, $cleanReal);

        $cleanMain = '<?php
// Universal vendor/autoload.php @generated by OmniMart Repair
require_once __DIR__ . "/composer/autoload_real.php";
return ComposerAutoloaderUniversal::getLoader();
';
        file_put_contents($mainAutoloadFile, $cleanMain);
        $msg[] = "Universal dynamic autoloader installed (hash-independent, 100% stable).";
        return $msg;
    }

    // Try synchronizing hash between static and real
    $staticContent = @file_get_contents($staticFile);
    if (preg_match('/class\s+(ComposerStaticInit[a-f0-9]+)/', $staticContent, $sm)) {
        $foundClass = $sm[1];
        $foundHash = substr($foundClass, strlen('ComposerStaticInit'));

        $realContent = @file_get_contents($realFile);
        if (preg_match('/(ComposerStaticInit[a-f0-9]+)/', $realContent, $rm)) {
            $currentClassInReal = $rm[1];
            $currentHashInReal = substr($currentClassInReal, strlen('ComposerStaticInit'));

            if ($currentHashInReal !== $foundHash) {
                $newRealContent = str_replace($currentHashInReal, $foundHash, $realContent);
                file_put_contents($realFile, $newRealContent);

                if (file_exists($mainAutoloadFile)) {
                    $mainContent = @file_get_contents($mainAutoloadFile);
                    $newMainContent = str_replace($currentHashInReal, $foundHash, $mainContent);
                    file_put_contents($mainAutoloadFile, $newMainContent);
                }
                $msg[] = "Synchronized autoloader hash from {$currentHashInReal} to {$foundHash}.";
            }
        }
    } else {
        // Fallback to dynamic loader
        return repairComposerAutoloader(true);
    }

    return $msg;
}

// Auto-sync packages/stancl into vendor/stancl if missing
$vendorStanclDir = __DIR__ . '/../vendor/stancl';
$packagesStanclDir = __DIR__ . '/../packages/stancl';
if (!file_exists($vendorStanclDir . '/tenancy/src/TenancyServiceProvider.php') && is_dir($packagesStanclDir)) {
    if (function_exists('omnimart_sync_dir')) {
        omnimart_sync_dir($packagesStanclDir, $vendorStanclDir);
    } else {
        function omnimart_sync_dir_boot($src, $dst) {
            if (!is_dir($src)) return;
            if (!is_dir($dst)) @mkdir($dst, 0755, true);
            $dir = @opendir($src);
            if (!$dir) return;
            while (false !== ($file = readdir($dir))) {
                if ($file === '.' || $file === '..') continue;
                $s = $src . '/' . $file;
                $d = $dst . '/' . $file;
                if (is_dir($s)) {
                    omnimart_sync_dir_boot($s, $d);
                } elseif (!file_exists($d)) {
                    @copy($s, $d);
                }
            }
            closedir($dir);
        }
        omnimart_sync_dir_boot($packagesStanclDir, $vendorStanclDir);
    }
}

// Auto-sync packages/doctrine into vendor/doctrine if missing
$vendorDoctrineDir = __DIR__ . '/../vendor/doctrine/inflector';
